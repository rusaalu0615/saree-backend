import mongoose from "mongoose";

/**
 * Durable transactional-email outbox.
 *
 * Payment/shipping success must NEVER depend on SMTP. Success paths enqueue a
 * job atomically with their state transition; this collection is the single
 * source of delivery truth. A process restart cannot lose a notification, and
 * a failing SMTP provider produces bounded retries with backoff plus an
 * explicit `manual_review` state instead of silent disappearance.
 */
const emailJobSchema = new mongoose.Schema({
    // Idempotency: one confirmation mail per order, one update per (order,status)
    dedupeKey: { type: String, required: true, unique: true },
    kind: {
        type: String,
        enum: ["order_confirmation", "admin_order_notification", "shipping_update"],
        required: true,
    },
    order: { type: mongoose.Schema.Types.ObjectId, ref: "Order", required: true, index: true },
    // For shipping_update jobs the status the customer should be told about.
    statusParam: String,
    // Invoice PDF is generated by the worker from the order at send time
    // (nothing heavy stored here).
    state: {
        type: String,
        // "skipped" is a deliberate, non-failure terminal outcome (e.g. a
        // shipping status that has no customer email) — distinct from "sent" so
        // the outbox never reports a message that was never actually delivered.
        enum: ["queued", "in_flight", "sent", "skipped", "failed_permanent", "manual_review"],
        default: "queued",
    },
    attempts: { type: Number, default: 0 },
    maxAttempts: { type: Number, default: 6 },
    nextAttemptAt: { type: Date, default: Date.now },
    leaseOwner: String,
    leaseExpiresAt: Date,
    lastError: String,
    sentAt: Date,
}, { timestamps: true });

emailJobSchema.index({ state: 1, nextAttemptAt: 1 });

export default mongoose.model("EmailJob", emailJobSchema);
